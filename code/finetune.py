"""
Phase 2: Fine-tune a local model for Stage 0 query extraction.

Uses QLoRA (4-bit quantized base + LoRA adapters) to fine-tune a small
model on the training data generated by generate_training_data.py.

Requirements:
  pip install transformers peft bitsandbytes trl datasets accelerate torch

Usage:
  # Fine-tune (needs GPU with >= 6GB VRAM, or use CPU with --no-quantize)
  python finetune.py --data training_data/chat_pairs.jsonl

  # Fine-tune with custom settings
  python finetune.py --data training_data/chat_pairs.jsonl \
      --model Qwen/Qwen2.5-1.5B-Instruct \
      --epochs 3 \
      --output models/query-parser

  # Test the fine-tuned model
  python finetune.py --test --model-path models/query-parser \
      --query "Logistics companies in Romania with over 50 employees"

  # Export for Ollama
  python finetune.py --export-ollama --model-path models/query-parser
"""

import json
import os
import sys
import argparse
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

# ── Default config ───────────────────────────────────────────────────────

DEFAULT_MODEL = "Qwen/Qwen2.5-1.5B-Instruct"  # Small, fast, good at JSON
DEFAULT_OUTPUT = "models/query-parser"
DEFAULT_EPOCHS = 3
DEFAULT_BATCH_SIZE = 4
DEFAULT_LR = 2e-4
LORA_RANK = 16
LORA_ALPHA = 32
LORA_DROPOUT = 0.05
MAX_SEQ_LENGTH = 512  # Our inputs/outputs are short


def train(args):
    """Main training loop."""
    import torch
    from datasets import load_dataset
    from transformers import (
        AutoModelForCausalLM,
        AutoTokenizer,
        BitsAndBytesConfig,
        TrainingArguments,
    )
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
    from trl import SFTTrainer, SFTConfig

    # ── Check data ───────────────────────────────────────────────
    if not os.path.exists(args.data):
        logger.error(f"Training data not found: {args.data}")
        logger.error("Run generate_training_data.py first.")
        sys.exit(1)

    eval_path = args.data.replace(".jsonl", "_eval.jsonl")
    has_eval = os.path.exists(eval_path)

    # Count samples
    with open(args.data) as f:
        n_train = sum(1 for _ in f)
    logger.info(f"Training samples: {n_train}")
    if has_eval:
        with open(eval_path) as f:
            n_eval = sum(1 for _ in f)
        logger.info(f"Eval samples: {n_eval}")

    if n_train < 50:
        logger.warning(f"Only {n_train} training samples. Recommend 200+ for good results.")

    # ── Load tokenizer ───────────────────────────────────────────
    logger.info(f"Loading tokenizer: {args.model}")
    tokenizer = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    # ── Load model (quantized or full) ───────────────────────────
    device = "cuda" if torch.cuda.is_available() else "cpu"
    logger.info(f"Device: {device}")

    if device == "cuda" and not args.no_quantize:
        logger.info("Loading model with 4-bit quantization (QLoRA)")
        bnb_config = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16,
            bnb_4bit_use_double_quant=True,
        )
        model = AutoModelForCausalLM.from_pretrained(
            args.model,
            quantization_config=bnb_config,
            device_map="auto",
            trust_remote_code=True,
        )
        model = prepare_model_for_kbit_training(model)
    else:
        if device == "cpu":
            logger.info("Loading model in float32 (CPU mode, slower)")
        else:
            logger.info("Loading model without quantization")
        model = AutoModelForCausalLM.from_pretrained(
            args.model,
            torch_dtype=torch.float32 if device == "cpu" else torch.bfloat16,
            device_map="auto" if device == "cuda" else None,
            trust_remote_code=True,
        )

    # ── LoRA config ──────────────────────────────────────────────
    lora_config = LoraConfig(
        r=LORA_RANK,
        lora_alpha=LORA_ALPHA,
        lora_dropout=LORA_DROPOUT,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                        "gate_proj", "up_proj", "down_proj"],
    )

    model = get_peft_model(model, lora_config)
    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    total = sum(p.numel() for p in model.parameters())
    logger.info(f"Trainable params: {trainable:,} / {total:,} ({100 * trainable / total:.2f}%)")

    # ── Load dataset ─────────────────────────────────────────────
    dataset = load_dataset("json", data_files=args.data, split="train")
    eval_dataset = None
    if has_eval:
        eval_dataset = load_dataset("json", data_files=eval_path, split="train")

    # ── Format for chat template ─────────────────────────────────
    def format_chat(example):
        """Apply the tokenizer's chat template to format messages."""
        text = tokenizer.apply_chat_template(
            example["messages"],
            tokenize=False,
            add_generation_prompt=False,
        )
        return {"text": text}

    dataset = dataset.map(format_chat)
    if eval_dataset:
        eval_dataset = eval_dataset.map(format_chat)

    # ── Training config ──────────────────────────────────────────
    output_dir = args.output
    os.makedirs(output_dir, exist_ok=True)

    training_args = SFTConfig(
        output_dir=output_dir,
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.batch_size,
        gradient_accumulation_steps=max(1, 16 // args.batch_size),
        learning_rate=args.lr,
        weight_decay=0.01,
        warmup_ratio=0.1,
        logging_steps=10,
        save_strategy="epoch",
        eval_strategy="epoch" if eval_dataset else "no",
        bf16=device == "cuda",
        max_seq_length=MAX_SEQ_LENGTH,
        dataset_text_field="text",
        report_to="none",
    )

    # ── Train ────────────────────────────────────────────────────
    trainer = SFTTrainer(
        model=model,
        args=training_args,
        train_dataset=dataset,
        eval_dataset=eval_dataset,
        processing_class=tokenizer,
    )

    logger.info("Starting training...")
    trainer.train()

    # ── Save ─────────────────────────────────────────────────────
    # Save only the LoRA adapters (small, ~50-100MB)
    adapter_path = os.path.join(output_dir, "adapter")
    model.save_pretrained(adapter_path)
    tokenizer.save_pretrained(adapter_path)

    # Save config for inference
    config = {
        "base_model": args.model,
        "adapter_path": "adapter",
        "lora_rank": LORA_RANK,
        "lora_alpha": LORA_ALPHA,
        "max_seq_length": MAX_SEQ_LENGTH,
        "training_samples": n_train,
        "epochs": args.epochs,
    }
    with open(os.path.join(output_dir, "config.json"), "w") as f:
        json.dump(config, f, indent=2)

    logger.info(f"Model saved to {output_dir}/")
    logger.info(f"  Adapter: {adapter_path}/ (~{_dir_size_mb(adapter_path):.0f} MB)")
    logger.info(f"  Config:  {output_dir}/config.json")


def test_model(args):
    """Test inference with a fine-tuned model."""
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import PeftModel

    model_path = args.model_path
    config_path = os.path.join(model_path, "config.json")

    if not os.path.exists(config_path):
        logger.error(f"Config not found: {config_path}")
        sys.exit(1)

    with open(config_path) as f:
        config = json.load(f)

    base_model_name = config["base_model"]
    adapter_path = os.path.join(model_path, config["adapter_path"])

    logger.info(f"Loading base model: {base_model_name}")
    device = "cuda" if torch.cuda.is_available() else "cpu"

    tokenizer = AutoTokenizer.from_pretrained(base_model_name, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        base_model_name,
        torch_dtype=torch.float32 if device == "cpu" else torch.bfloat16,
        device_map="auto" if device == "cuda" else None,
        trust_remote_code=True,
    )

    logger.info(f"Loading LoRA adapter: {adapter_path}")
    model = PeftModel.from_pretrained(model, adapter_path)
    model.eval()

    # System prompt (same as training)
    system_prompt = """You are a query parser for a company search engine. Extract structured information from the user's query.

Return ONLY valid JSON with these fields (use null for fields not mentioned in the query):
{
  "locations": ["list of countries, regions, or cities mentioned"],
  "employee_count_min": number or null,
  "employee_count_max": number or null,
  "revenue_min": number in USD or null,
  "revenue_max": number in USD or null,
  "year_founded_min": number or null,
  "year_founded_max": number or null,
  "is_public": true/false/null,
  "industry_keywords": ["list of relevant industry terms, products, services"],
  "business_model_keywords": ["B2B", "B2C", "SaaS", "marketplace", etc. or empty list],
  "complexity": "simple" | "moderate" | "complex"
}

Rules:
- For revenue, always convert to raw USD (e.g., "$50 million" → 50000000)
- For locations, include the actual place names as mentioned (e.g., "Scandinavia", "Germany", "Berlin")
- For industry_keywords, expand beyond the exact words used — include synonyms and related terms
- complexity is "simple" if only basic filters, "moderate" if needs semantic matching, "complex" if requires reasoning about supply chains, competition, or indirect relationships
- Do NOT invent constraints that aren't in the query"""

    # Test queries
    queries = [args.query] if args.query else [
        "Logistics companies in Romania",
        "Public software companies with more than 1,000 employees",
        "Clean energy startups founded after 2018 with fewer than 200 employees in Scandinavia",
        "Companies that could supply packaging materials for a direct-to-consumer cosmetics brand",
        "B2B SaaS companies providing HR solutions in Europe",
    ]

    for query in queries:
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": query},
        ]

        input_text = tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )
        inputs = tokenizer(input_text, return_tensors="pt").to(model.device)

        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_new_tokens=300,
                temperature=0.0,
                do_sample=False,
                pad_token_id=tokenizer.pad_token_id,
            )

        # Decode only the generated tokens
        generated = outputs[0][inputs["input_ids"].shape[1]:]
        response = tokenizer.decode(generated, skip_special_tokens=True).strip()

        print(f"\n{'─' * 60}")
        print(f"Query: {query}")
        print(f"{'─' * 60}")

        try:
            parsed = json.loads(response)
            print(json.dumps(parsed, indent=2))
        except json.JSONDecodeError:
            print(f"[RAW OUTPUT — not valid JSON]")
            print(response[:500])


def export_ollama(args):
    """Export the fine-tuned model as an Ollama Modelfile."""
    model_path = args.model_path
    config_path = os.path.join(model_path, "config.json")

    if not os.path.exists(config_path):
        logger.error(f"Config not found: {config_path}")
        sys.exit(1)

    with open(config_path) as f:
        config = json.load(f)

    # First, merge LoRA weights into base model
    logger.info("Merging LoRA adapter into base model...")
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import PeftModel

    tokenizer = AutoTokenizer.from_pretrained(config["base_model"], trust_remote_code=True)
    base_model = AutoModelForCausalLM.from_pretrained(
        config["base_model"],
        torch_dtype=torch.float16,
        device_map="cpu",
        trust_remote_code=True,
    )

    adapter_path = os.path.join(model_path, config["adapter_path"])
    model = PeftModel.from_pretrained(base_model, adapter_path)
    merged = model.merge_and_unload()

    merged_path = os.path.join(model_path, "merged")
    merged.save_pretrained(merged_path)
    tokenizer.save_pretrained(merged_path)
    logger.info(f"Merged model saved to {merged_path}/")

    # Create Modelfile
    modelfile = f"""FROM {merged_path}

PARAMETER temperature 0
PARAMETER num_predict 300

SYSTEM \"\"\"You are a query parser for a company search engine. Extract structured information from the user's query. Return ONLY valid JSON.\"\"\"
"""

    modelfile_path = os.path.join(model_path, "Modelfile")
    with open(modelfile_path, "w") as f:
        f.write(modelfile)

    logger.info(f"Ollama Modelfile saved to {modelfile_path}")
    logger.info(f"To create: ollama create query-parser -f {modelfile_path}")


def _dir_size_mb(path: str) -> float:
    """Get directory size in MB."""
    total = 0
    for dirpath, _, filenames in os.walk(path):
        for f in filenames:
            total += os.path.getsize(os.path.join(dirpath, f))
    return total / (1024 * 1024)


def main():
    parser = argparse.ArgumentParser(description="Fine-tune a local model for Stage 0")
    subparsers = parser.add_subparsers(dest="command")

    # Default: train
    parser.add_argument("--data", default="training/chat_pairs.jsonl",
                        help="Training data path")
    parser.add_argument("--model", default=DEFAULT_MODEL, help="Base model name")
    parser.add_argument("--output", default=DEFAULT_OUTPUT, help="Output directory")
    parser.add_argument("--epochs", type=int, default=DEFAULT_EPOCHS)
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    parser.add_argument("--lr", type=float, default=DEFAULT_LR)
    parser.add_argument("--no-quantize", action="store_true",
                        help="Disable 4-bit quantization (for CPU or testing)")

    # Test mode
    parser.add_argument("--test", action="store_true", help="Test a fine-tuned model")
    parser.add_argument("--model-path", default=DEFAULT_OUTPUT,
                        help="Path to fine-tuned model")
    parser.add_argument("--query", help="Single query to test")

    # Export mode
    parser.add_argument("--export-ollama", action="store_true",
                        help="Export for Ollama")

    args = parser.parse_args()

    if args.test:
        test_model(args)
    elif args.export_ollama:
        export_ollama(args)
    else:
        train(args)


if __name__ == "__main__":
    main()